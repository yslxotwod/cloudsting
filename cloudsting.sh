# ── dispatch ────────────────────────────────────────────────────────
cs_main() {
    local verb="${1:-menu}"
    shift || true
    case "$verb" in
        menu)          cs_cmd_menu "$@" ;;
        list|ls)       cs_cmd_list "$@" ;;
        info)          cs_cmd_info "$@" ;;
        run|r)         cs_cmd_run "$@" ;;
        selftest|test) cs_cmd_selftest "$@" ;;
        status)        cs_cmd_status "$@" ;;
        loot|results)  cs_cmd_loot "$@" ;;
        playbook|pb)   cs_cmd_playbook "$@" ;;
        findings)      cs_cmd_findings "$@" ;;
        session|whoami) cs_cmd_session "$@" ;;
        registry)      cs_cmd_registry "$@" ;;
        deps)          cs_cmd_deps "$@" ;;
        completion|comp) cs_cmd_completion "$@" ;;
        man)           cs_cmd_man ;;
        version|--version|-V) printf 'cloudsting %s\n' "$CS_VERSION" ;;
        help|--help|-h) cs_cmd_help ;;
        *)             cs_usage_die "unknown verb: $verb" ;;
    esac
}

cs_main "$@"
