# ── verb: man ───────────────────────────────────────────────────────
cs_cmd_man() {
    cat <<'MAN'
CLOUDSTING(1)                     cloudsting                     CLOUDSTING(1)

NAME
       cloudsting - cloud and API attack-surface toolkit

SYNOPSIS
       cloudsting menu
       cloudsting list
