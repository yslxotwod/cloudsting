DESCRIPTION
       cloudsting is a launcher over standalone shell modules. Each module
       answers one question about a cloud account or an API surface and
       writes tab-separated rows.  The launcher never interprets module
       arguments: `cloudsting run 03 --domain example.com` is exactly
       `modules/03_bucket_enum.sh --domain example.com`.

MODULES
       A module is referenced by number ("3", "03"), by slug
       ("03_bucket_enum", "bucket_enum") or by title ("Bucket Enum").
       `cloudsting menu` lists all three.

VERBS
       menu        Every module with category, slug and one-line mission.
       list        id, slug, title, category - one row per module.
       info        Metadata for one module plus its on-disk script path.
       run         Execute one module; argv is passed through untouched and
                   the module's exit code becomes the launcher's.
       selftest    Run every module's offline self-test, or one module's.
                   No credentials, no network.
       status      One row per module: what it thinks its own provider and
                   tool state is.  Three states, never collapsed:
                   tool-missing, creds-missing, creds-present.
       loot        Recent loot files, newest first, with size and timestamp.
       playbook    Run a chained playbook from data/playbooks/<name>.play.
                   Each step's stdout is fed to the next step's stdin.
       findings    The unified findings store at loot/findings.tsv: append
                   rows from any module so one query spans the whole run.
       registry    Emit the module registry (TSV, JSON or header) so a
                   viewer can render the tree without its own table.
       deps        Run module 00's dependency report.

PLAYBOOK FORMAT
       data/playbooks/<name>.play, one directive per line:

           #desc: one line describing the chain
           set VAR=value
           module 01 --status-tsv
           module 03 --domain "$TARGET"
           stop-on-fail | continue

EXIT STATUS
       0  the operation completed
       1  the operation failed, or a self-test failed
       2  usage error
       3  a module file is missing

ENVIRONMENT
       CLOUDSTING_ROOT    project root; resolved from the script path when unset
       CLOUDSTING_LOOT    where results land (default: <root>/loot)
       CLOUDSTING_STATE   where the GUI keeps its memory (default: <root>/state)
       CLOUDSTING_TMP     scratch space (default: <root>/tmp)
       NO_COLOR           set to any value to disable colour

FILES
       data/registry.tsv        module registry (generated, committed)
       lt;root>/loot/findings.tsv   unified findings store
       <root>/modules/*.sh      the modules themselves

