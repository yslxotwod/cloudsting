#!/usr/bin/env bash
# cloudsting.sh — CLI launcher and module registry for the cloudsting toolkit
#
# This file is the single source of truth for what a module is: its number,
# its slug, its title, its category, its one-line mission, the verbs it
# exposes and where its output lands. The GUI reads the same registry through
# `cloudsting registry --tsv` instead of carrying its own copy in C.
#
# Contract:
#   - bash 4.2+ (no associative-array ordering assumptions, no mapfile-only)
#   - every public verb is TSV or plain text on stdout, diagnostics on stderr
#   - exit 0 ok · 1 refusal/failure · 2 usage · 3 missing prerequisite
set -Eeuo pipefail
IFS=$'\n\t'

# ── self-location ───────────────────────────────────────────────────
# Resolve the project root from this script's own path so the launcher works
# from any cwd, through any symlink, and under pkexec/sudo where $HOME moved.
_cs_self_dir() {
    local src="${BASH_SOURCE[0]}" dir
    while [[ -L "$src" ]]; do
        dir="$(cd -P "$(dirname "$src")" && pwd)"
        src="$(readlink "$src")"
        [[ "$src" != /* ]] && src="$dir/$src"
    done
    # the script may be invoked by a bare relative name: make it absolute
    # before taking its dirname, or `cd ..` walks up from $PWD instead.
    [[ "$src" == /* ]] || src="$PWD/$src"
    cd -P "$(dirname "$src")" && pwd
}

# The launcher lives at <root>/cloudsting.sh or <root>/bin/cloudsting, so the
# root is the parent of whichever directory holds this file.
_cs_self_root() {
    local dir; dir="$(_cs_self_dir)"
    if [[ -d "$dir/modules" ]]; then printf '%s' "$dir"; return; fi
    if [[ -d "$dir/../modules" ]]; then (cd -P "$dir/.." && pwd); return; fi
    printf '%s' "$dir"
}

CS_ROOT="$(_cs_self_root)"
export CLOUDSTING_ROOT="$CS_ROOT"
CS_MODULES="$CS_ROOT/modules"
CS_REGISTRY="$CS_ROOT/data/registry.tsv"
CS_LOOT="${CLOUDSTING_LOOT:-$CS_ROOT/loot}"
CS_STATE="${CLOUDSTING_STATE:-$CS_ROOT/state}"
CS_TMP="${CLOUDSTING_TMP:-$CS_ROOT/tmp}"
CS_LOGS="${CLOUDSTING_LOGS:-$CS_ROOT/logs}"
CS_VERSION="$(cat "$CS_ROOT/VERSION" 2>/dev/null || printf '0')"
CS_SCHEMA=1

export CLOUDSTING_LOOT="$CS_LOOT" CLOUDSTING_STATE="$CS_STATE"
export CLOUDSTING_TMP="$CS_TMP" CLOUDSTING_LOGS="$CS_LOGS"

# The provider gate, the TSV writer and the selftest ledger live in the shared
# core, the same file every module sources. The launcher uses them too, so
# `session` and `status` answer with the modules' own state machine instead of
# a second implementation of it.
# shellcheck source=data/lib/core.sh
# shellcheck disable=SC1091
source "$CS_ROOT/data/lib/core.sh"

# ── output ──────────────────────────────────────────────────────────
if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
    C_RED=$'\033[31m'; C_GRN=$'\033[32m'; C_YEL=$'\033[33m'
    C_CYN=$'\033[36m'; C_DIM=$'\033[2m'; C_BLD=$'\033[1m'; C_RST=$'\033[0m'
else
    C_RED=''; C_GRN=''; C_YEL=''; C_CYN=''; C_DIM=''; C_BLD=''; C_RST=''
fi

cs_say()  { printf '%s\n' "$*"; }
cs_err()  { printf '%scs:%s %s\n' "$C_RED" "$C_RST" "$*" >&2; }
cs_note() { printf '%s%s%s\n' "$C_DIM" "$*" "$C_RST" >&2; }
cs_die()  { cs_err "$*"; exit "${CS_DIE_CODE:-1}"; }
cs_usage_die() { cs_err "$*"; cs_err "run 'cloudsting help' for the verb list"; exit 2; }

# ── registry ────────────────────────────────────────────────────────
# data/registry.tsv columns:
#   1 id        07                      (numeric, used by `cloudsting run 07`)
#   2 slug      07_policy_audit         (stable id; matches the script basename)
#   3 title     Policy Audit
#   4 category  SETUP|CREDS|IDENTITY|SURFACE|COMPUTE|STORAGE|NETWORK|DNS|ATTRITION|WEBAPI|TOOLING
#   5 mission   one line, what it answers
#   6 verbs     space separated flags the module documents
#   7 selftest  count of checks, or '-' when the module has none
#   8 phase     which build phase shipped it (0-11)
#
# The file is generated by `cloudsting registry --generate` from the module
# scripts' own --help; the committed copy is the fast path and the authority
# for titles and missions, which a script cannot self-describe well.

cs_registry_ok() {
    [[ -r "$CS_REGISTRY" ]] || return 1
    [[ "$(head -1 "$CS_REGISTRY" 2>/dev/null | cut -f1)" == "id" ]] || return 1
    return 0
}

# Strip the header, keep data rows.
cs_registry_rows() {
    if cs_registry_ok; then
        awk -F'\t' 'NR>1 && NF>=8 && $1 !~ /^#/' "$CS_REGISTRY"
    else
        # Fallback: derive a minimal registry straight from the modules tree so
        # a fresh checkout without the generated file still lists and runs.
        local f base num
        for f in "$CS_MODULES"/*.sh; do
            [[ -e "$f" ]] || continue
            base="$(basename "$f" .sh)"
            num="${base%%_*}"
            [[ "$num" =~ ^[0-9]+$ ]] || continue
            printf '%s\t%s\t%s\t%s\t%s\t-\t-\t0\n' \
                "$num" "$base" "${base#*_}" "UNKNOWN" "no mission recorded"
        done
    fi
}

# Resolve a user-supplied module reference to a registry row.
#   "7"  "07"  "07_policy_audit"  "policy_audit"  "Policy Audit"
cs_resolve() {
    local want="${1:-}" rows row slug num
    [[ -n "$want" ]] || return 1

    # numeric shorthands: 7 -> 07
    if [[ "$want" =~ ^[0-9]{1,2}$ ]]; then
        printf -v num '%02d' "$((10#$want))"
        want="$num"
    fi

    rows="$(cs_registry_rows)"
    [[ -n "$rows" ]] || return 1

    # exact slug, exact numeric id
    row="$(printf '%s\n' "$rows" | awk -F'\t' -v w="$want" '$2==w || $1==w {print; exit}')"
    [[ -n "$row" ]] || {
        # bare slug without the number, e.g. "policy_audit"
        row="$(printf '%s\n' "$rows" | awk -F'\t' -v w="$want" '
            { slug=$2; sub(/^[0-9]+_/, "", slug); if (slug==w) { print; exit } }')"
    }
    [[ -n "$row" ]] || {
        # title, case-insensitive
        row="$(printf '%s\n' "$rows" | awk -F'\t' -v w="$want" '
            { if (tolower($3)==tolower(w)) { print; exit } }')"
    }
    [[ -n "$row" ]] || return 1
    printf '%s\n' "$row"
}

cs_get() {  # cs_get <row> <field 1-8>
    printf '%s' "$1" | awk -F'\t' -v n="$2" '{print $n}'
}

cs_slug()   { cs_get "$1" 2; }
cs_number() { cs_get "$1" 1; }
cs_title()  { cs_get "$1" 3; }
cs_cat()    { cs_get "$1" 4; }
cs_mission() { cs_get "$1" 5; }
cs_verbs()  { cs_get "$1" 6; }

cs_script_for() {  # cs_script_for <row>
    printf '%s/%s.sh' "$CS_MODULES" "$(cs_slug "$1")"
}

# ── verb: menu ──────────────────────────────────────────────────────
cs_cmd_menu() {
    local rows row cat last_cat=""
    rows="$(cs_registry_rows)"
    [[ -n "$rows" ]] || cs_die "no modules found under $CS_MODULES"

    printf '%scloudsting %s%s — %s modules\n' "$C_BLD" "$CS_VERSION" "$C_RST" \
        "$(printf '%s\n' "$rows" | wc -l | tr -d ' ')"
    printf '%s%s%s\n\n' "$C_DIM" "run: cloudsting run <nn|slug> [--verb args…]    all:  cloudsting run all --status-tsv" "$C_RST"

    while IFS= read -r row; do
        [[ -n "$row" ]] || continue
        cat="$(cs_cat "$row")"
        if [[ "$cat" != "$last_cat" ]]; then
            printf '\n%s%s%s\n' "$C_CYN" "$cat" "$C_RST"
            last_cat="$cat"
        fi
        printf '  %s%s%s  %-26s %s\n' "$C_BLD" "$(cs_number "$row")" "$C_RST" \
            "$(cs_slug "$row")" "$(cs_mission "$row")"
    done <<<"$rows"
    printf '\n'
}

# ── verb: list ──────────────────────────────────────────────────────
cs_cmd_list() {
    cs_registry_rows | awk -F'\t' '{printf "%s\t%s\t%s\t%s\n", $1, $2, $3, $4}'
}

# ── verb: registry ──────────────────────────────────────────────────
# Every field for every module, so a viewer (the GUI) never needs its own table.
cs_cmd_registry() {
    local mode="${1:---tsv}"
    case "$mode" in
        --tsv|"")   cs_registry_rows ;;
        --header)   cs_registry_ok && cat "$CS_REGISTRY" ;;
        --json)
            cs_registry_rows | awk -F'\t' '
                BEGIN { printf "[" }
                {
                    if (NR > 1) printf ","
                    gsub(/\\/, "\\\\"); gsub(/"/, "\\\"")
                    printf "{\"id\":%s,\"slug\":\"%s\",\"title\":\"%s\",\"category\":\"%s\",\"mission\":\"%s\",\"verbs\":\"%s\"}", \
                        $1, $2, $3, $4, $5, $6
                }
                END { printf "]\n" }'
            ;;
        --field)
            local field="${2:?field name required}"
            case "$field" in
                id) 1 ;; slug) 2 ;; title) 3 ;; category) 4 ;;
                mission) 5 ;; verbs) 6 ;; selftest) 7 ;; phase) 8 ;;
                *) cs_usage_die "unknown field: $field" ;;
            esac | xargs -r printf ''
            ;;
        --generate) cs_cmd_registry_generate ;;
        *) cs_usage_die "registry: unknown mode $mode" ;;
    esac
}

# Regenerate data/registry.tsv from the module scripts themselves, keeping the
# committed titles/missions/categories where a row already exists.
cs_cmd_registry_generate() {
    local tmp slug num verbs selftest title cat mission phase
    tmp="$(mktemp)"
    printf 'id\tslug\ttitle\tcategory\tmission\tverbs\tselftest\tphase\n' > "$tmp"

    for f in "$CS_MODULES"/*.sh; do
        [[ -e "$f" ]] || continue
        slug="$(basename "$f" .sh)"
        num="${slug%%_*}"
        [[ "$num" =~ ^[0-9]+$ ]] || continue

        verbs="$(bash "$f" --help 2>/dev/null \
            | grep -oE -- '--[a-z][a-z0-9-]+' | sort -u | tr '\n' ' ' | sed 's/ *$//')" || verbs=""

        # count every check the suite ran: `ok\t<name>`, `<name>\tPASS` and the
        # final `RESULT\tPASS(n)` all mean the same thing — count pass lines,
        # and fall back to the RESULT tally when the suite prints only that.
        selftest="$(timeout 120 bash "$f" --selftest 2>/dev/null \
            | awk -F'\t' '
                $1=="RESULT" { if ($2 ~ /PASS\(/) { print substr($2, 6, length($2)-6); hit=1 }
                               else if ($2=="PASS") { print n; hit=1 } }
                $1=="ok" { n++ }
                NF>=2 && $2=="PASS" { n++ }
                END { if (!hit && n>0) print n }' | tail -1)" || selftest=""
        [[ -n "${selftest:-}" ]] || selftest="-"

        # preserve what the committed registry already knows about this slug:
        # read one field at a time so a title or mission containing spaces or
        # punctuation survives instead of being split on whitespace.
        title="" cat="" mission="" phase=""
        # the hand-owned table is the source of truth for category, phase,
        # title and mission — it survives a merge, a rename and a bulk edit
        # that no code could infer. Verbs and the selftest tally are measured.
        if [[ -f "$CS_ROOT/data/registry.cat" ]]; then
            local orow
            orow="$(awk -F'\t' -v i="$num" '$1==i {print; exit}' "$CS_ROOT/data/registry.cat")"
            if [[ -n "$orow" ]]; then
                cat="$(printf '%s' "$orow" | cut -f2)"
                phase="$(printf '%s' "$orow" | cut -f3)"
                title="$(printf '%s' "$orow" | cut -f4)"
                mission="$(printf '%s' "$orow" | cut -f5)"
            fi
        elif cs_registry_ok; then
            local row
            row="$(awk -F'\t' -v s="$slug" '$2==s {print; exit}' "$CS_REGISTRY")"
            if [[ -n "$row" ]]; then
                title="$(printf '%s' "$row" | cut -f3)"
                cat="$(printf '%s' "$row" | cut -f4)"
                mission="$(printf '%s' "$row" | cut -f5)"
                phase="$(printf '%s' "$row" | cut -f8)"
            fi
        fi
        title="${title:-${slug#*_}}"
        cat="${cat:-UNKNOWN}"
        mission="${mission:-no mission recorded}"
        phase="${phase:-1}"

        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
            "$num" "$slug" "$title" "$cat" "$mission" "$verbs" "$selftest" "$phase" >> "$tmp"
    done

    { head -1 "$tmp"; awk -F'\t' 'NR>1 && $1 ~ /^[0-9]+$/' "$tmp" | sort -t$'\t' -k1,1n; } > "$CS_REGISTRY.new"
    mv "$CS_REGISTRY.new" "$CS_REGISTRY"
    rm -f "$tmp"
    printf 'WROTE\t%s\n' "$CS_REGISTRY"
    printf 'ROWS\t%s\n' "$(( $(wc -l < "$CS_REGISTRY") - 1 ))"
}

# ── verb: info ──────────────────────────────────────────────────────
cs_cmd_info() {
    local row
    row="$(cs_resolve "${1:-}")" || cs_usage_die "unknown module: ${1:-<none>}"
    local script; script="$(cs_script_for "$row")"

    printf 'MODULE\t%s\n' "$(cs_slug "$row")"
    printf 'NUMBER\t%s\n' "$(cs_number "$row")"
    printf 'TITLE\t%s\n'  "$(cs_title "$row")"
    printf 'CATEGORY\t%s\n' "$(cs_cat "$row")"
    printf 'MISSION\t%s\n' "$(cs_mission "$row")"
    printf 'SCRIPT\t%s\n' "$script"
    printf 'EXECUTABLE\t%s\n' "$([[ -x "$script" ]] && echo yes || echo no)"
    printf 'SELFTEST\t%s\n' "$(cs_get "$row" 7)"
    printf 'PHASE\t%s\n'   "$(cs_get "$row" 8)"
    printf 'LOOT\t%s\n'    "$CS_LOOT"
    printf 'VERBS\t%s\n'   "$(cs_verbs "$row")"
}

# ── verb: run ───────────────────────────────────────────────────────
# `cloudsting run 03 --domain example.com` execs modules/03_bucket_enum.sh
# with argv passed through untouched. Nothing is rewritten, nothing is
# interpreted: the module's own `--help` stays the authority.
cs_cmd_run() {
    local ref="${1:-}"
    [[ -n "$ref" ]] || cs_usage_die "run: module required (cloudsting run <nn|slug> [args…])"
    shift || true

    local row script
    row="$(cs_resolve "$ref")" || cs_usage_die "unknown module: $ref"
    script="$(cs_script_for "$row")"
    [[ -f "$script" ]] || { cs_err "module file missing: $script"; exit 3; }

    # exec keeps the module's exit code, its signals and its stdout exactly
    if [[ -x "$script" ]]; then
        exec "$script" "$@"
    else
        exec bash "$script" "$@"
    fi
}

# ── verb: selftest ──────────────────────────────────────────────────
cs_cmd_selftest() {
    local want="${1:-all}"
    local rc=0 pass=0 fail=0 skip=0 slug script last line status

    if [[ "$want" != "all" ]]; then
        local row; row="$(cs_resolve "$want")" || cs_usage_die "unknown module: $want"
        script="$(cs_script_for "$row")"
        exec bash "$script" --selftest
    fi

    printf '%sselftest: every module, offline, no credentials%s\n\n' "$C_BLD" "$C_RST"
    while IFS= read -r row; do
        [[ -n "$row" ]] || continue
        slug="$(cs_slug "$row")"; script="$(cs_script_for "$row")"
        if [[ ! -f "$script" ]]; then
            printf '  %-30s %sMISSING%s\n' "$slug" "$C_YEL" "$C_RST"; skip=$((skip+1)); continue
        fi
        last="$(timeout 180 bash "$script" --selftest 2>/dev/null | tail -1)" || true
        case "$last" in
            RESULT*PASS*|*PASS*)
                printf '  %-30s %s%s%s\n' "$slug" "$C_GRN" "$last" "$C_RST"; pass=$((pass+1)) ;;
            *FAIL*)
                printf '  %-30s %s%s%s\n' "$slug" "$C_RED" "$last" "$C_RST"; fail=$((fail+1)); rc=1 ;;
            *)
                printf '  %-30s %sno result (%s)%s\n' "$slug" "$C_YEL" "${last:-empty}" "$C_RST"
                fail=$((fail+1)); rc=1 ;;
        esac
    done <<<"$(cs_registry_rows)"

    printf '\n%s passed · %s failed · %s missing\n' "$pass" "$fail" "$skip"
    return "$rc"
}

# ── verb: status ────────────────────────────────────────────────────
# One row per module: does it exist, is it executable, what does it know
# about its own provider/tool state. This is the honest run state.
cs_cmd_status() {
    local want="${1:-all}" row
    if [[ "$want" != "all" ]]; then
        row="$(cs_resolve "$want")" || cs_usage_die "unknown module: $want"
        local script; script="$(cs_script_for "$row")"
        printf 'module\t%s\n' "$(cs_slug "$row")"
        bash "$script" --status-tsv 2>/dev/null || printf 'status\tunavailable\n'
        return 0
    fi
    while IFS= read -r row; do
        [[ -n "$row" ]] || continue
        local script; script="$(cs_script_for "$row")"
        if [[ ! -f "$script" ]]; then
            printf '%s\tmissing\n' "$(cs_slug "$row")"
            continue
        fi
        # Modules differ in what their first status line carries: some lead
        # with `module<TAB>slug`, some with `provider<TAB>name<TAB>state`.
        # Lead every row with the slug and keep the whole report, so a caller
        # never has to know which shape it got.
        local out; out="$(timeout 20 bash "$script" --status-tsv 2>/dev/null)" || out=""
        if [[ -z "$out" ]]; then
            printf '%s\tno-status\n' "$(cs_slug "$row")"
            continue
        fi
        printf '%s\n' "$out" | while IFS= read -r line; do
            [[ -n "$line" ]] || continue
            printf '%s\t%s\n' "$(cs_slug "$row")" "$line"
        done
    done <<<"$(cs_registry_rows)"
}

# ── verb: session ───────────────────────────────────────────────────
# Who is on the end of these credentials, in one shape a viewer can render.
# This is what the GUI's session panel reads. Every field is answered even
# when nothing is authenticated — `state` is never collapsed, and an absent
# tool is not an empty account.
cs_cmd_session() {
    local mode="${1:---tsv}"

    # identity: module 06 knows how to ask AWS who it is talking to
    local acct="-" usr="-" uid="-" region="-" aws_state="tool-missing"
    local who; who="$(bash "$CS_MODULES/06_role_chains.sh" --whoami 2>/dev/null)" || who=""
    if [[ -n "$who" ]]; then
        acct="$(awk -F'\t' '$1=="account"{print $2}' <<<"$who")"; : "${acct:=-}"
        usr="$(awk -F'\t' '$1=="user"{print $2}' <<<"$who")";    : "${usr:=-}"
        uid="$(awk -F'\t' '$1=="userid"{print $2}' <<<"$who")";  : "${uid:=-}"
        region="$(awk -F'\t' '$1=="region"{print $2}' <<<"$who")"; : "${region:=-}"
        aws_state="$(awk -F'\t' '$1=="state"{print $2}' <<<"$who")"; : "${aws_state:=unknown}"
    fi

    # per-provider three-state, straight from the modules that own the gate
    local gcp_state az_state do_state oci_state k8s_state
    gcp_state="$(cs_provider_state gcloud)"
    az_state="$(cs_provider_state azure)"
    do_state="$(cs_provider_state digitalocean)"
    oci_state="$(cs_provider_state oci)"
    k8s_state="$(cs_provider_state kubectl)"

    # estate size: whatever the last inventory run counted
    local inv_file inv_rows="-" inv_ts="-"
    inv_file="$(ls -t "$CS_LOOT"/inventory/inventory-*.tsv 2>/dev/null | head -1 || true)"
    if [[ -n "${inv_file:-}" && -r "$inv_file" ]]; then
        inv_rows="$(wc -l < "$inv_file" | tr -d ' ')"
        inv_ts="$(date -u -r "$inv_file" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || echo '-')"
    fi

    # loot footprint
    local loot_rows loot_size
    loot_rows="$(find "$CS_LOOT" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | wc -l | tr -d ' ')"
    loot_size="$(du -sh "$CS_LOOT" 2>/dev/null | cut -f1 || echo '-')"
    : "${loot_size:=-}"

    case "$mode" in
        --tsv)
            printf 'key\tvalue\n'
            printf 'aws_account\t%s\n' "$acct"
            printf 'aws_user\t%s\n'    "$usr"
            printf 'aws_userid\t%s\n'  "$uid"
            printf 'aws_region\t%s\n'  "$region"
            printf 'aws_state\t%s\n'   "$aws_state"
            printf 'gcloud_state\t%s\n' "$gcp_state"
            printf 'azure_state\t%s\n'  "$az_state"
            printf 'doctl_state\t%s\n'  "$do_state"
            printf 'oci_state\t%s\n'    "$oci_state"
            printf 'k8s_state\t%s\n'    "$k8s_state"
            printf 'inventory_rows\t%s\n' "$inv_rows"
            printf 'inventory_ts\t%s\n'   "$inv_ts"
            printf 'loot_modules\t%s\n'   "$loot_rows"
            printf 'loot_size\t%s\n'      "$loot_size"
            printf 'root\t%s\n'           "$CS_ROOT"
            printf 'version\t%s\n'        "$CS_VERSION"
            ;;
        --json)
            printf '{"aws":{"account":"%s","user":"%s","userid":"%s","region":"%s","state":"%s"},' \
                "$acct" "$usr" "$uid" "$region" "$aws_state"
            printf '"providers":{"gcloud":"%s","azure":"%s","doctl":"%s","oci":"%s","k8s":"%s"},' \
                "$gcp_state" "$az_state" "$do_state" "$oci_state" "$k8s_state"
            printf '"inventory":{"rows":"%s","ts":"%s"},' "$inv_rows" "$inv_ts"
            printf '"loot":{"modules":"%s","size":"%s"},' "$loot_rows" "$loot_size"
            printf '"root":"%s","version":"%s"}\n' "$CS_ROOT" "$CS_VERSION"
            ;;
        --summary)
            # one line a panel header can draw
            printf 'aws %s' "$aws_state"
            [[ "$acct" != "-" ]] && printf ' · acct %s' "$acct"
            [[ "$region" != "-" ]] && printf ' · %s' "$region"
            printf ' · gcloud %s · azure %s · k8s %s' "$gcp_state" "$az_state" "$k8s_state"
            ;;
        --identities)
            # the raw four-key block, for a caller that wants to parse it
            printf 'account\t%s\nuser\t%s\nuserid\t%s\nregion\t%s\nstate\t%s\n' \
                "$acct" "$usr" "$uid" "$region" "$aws_state"
            ;;
        *) cs_usage_die "session: unknown mode $mode (--tsv --json --summary --identities)" ;;
    esac
}

# ── verb: loot ──────────────────────────────────────────────────────
# What came off a target last. Newest first, TSV so it pipes.
cs_cmd_loot() {
    local module_ref="${1:-}" limit="${2:-40}"
    local dir pattern
    if [[ -n "$module_ref" ]]; then
        local row; row="$(cs_resolve "$module_ref")" || cs_usage_die "unknown module: $module_ref"
        # modules write under either the numeric-prefixed dir or the bare slug
        for dir in "$CS_LOOT/$(cs_slug "$row" | sed 's/^[0-9]*_//')" "$CS_LOOT/$(cs_slug "$row")"; do
            [[ -d "$dir" ]] || continue
            find "$dir" -maxdepth 1 -type f -printf '%T@\t%p\t%s\n' 2>/dev/null
        done | sort -t$'\t' -k1,1nr | head -n "$limit" | awk -F'\t' -v m="$(cs_slug "$row")" '
            { ts=$1; sub(/\..*/,"",ts); cmd="date -u -d @" ts " +%Y-%m-%dT%H:%M:%SZ"; cmd | getline iso; close(cmd);
              n=split($2,p,"/"); printf "%s\t%s\t%s\t%s\n", m, iso, $3, p[n] }'
        return 0
    fi

    [[ -d "$CS_LOOT" ]] || { cs_note "no loot directory yet: $CS_LOOT"; return 0; }
    find "$CS_LOOT" -mindepth 2 -maxdepth 2 -type f -printf '%T@\t%p\t%s\n' 2>/dev/null \
        | sort -t$'\t' -k1,1nr | head -n "$limit" \
        | awk -F'\t' '
            { ts=$1; sub(/\..*/,"",ts); cmd="date -u -d @" ts " +%Y-%m-%dT%H:%M:%SZ"; cmd | getline iso; close(cmd);
              n=split($2,p,"/"); printf "%s\t%s\t%s\t%s\n", p[n-1], iso, $3, p[n] }'
}

# ── verb: playbook ──────────────────────────────────────────────────
# A playbook is a chain of modules that feeds one module's loot into the next.
# It exists because clicking twenty-three tiles is not a method.
cs_playbook_dir() { printf '%s/data/playbooks' "$CS_ROOT"; }

cs_cmd_playbook() {
    local name="${1:-}"; shift || true
    local dir; dir="$(cs_playbook_dir)"

    # Anything shaped KEY=VALUE after the name seeds the playbook's variables,
    # so `cloudsting playbook api-surface TARGET=.` works without editing files.
    local pair
    for pair in "$@"; do
        case "$pair" in
            *=*) export "$pair" ;;
        esac
    done

    if [[ -z "$name" ]]; then
        local f
        printf 'PLAYBOOK\tSTEPS\tWHAT IT DOES\n'
        for f in "$dir"/*.play; do
            [[ -e "$f" ]] || continue
            printf '%s\t%s\t%s\n' \
                "$(basename "$f" .play)" \
                "$(grep -cvE '^\s*(#|$)' "$f")" \
                "$(sed -n 's/^#desc:[[:space:]]*//p' "$f" | head -1)"
        done
        return 0
    fi

    local file="$dir/$name.play"
    [[ -r "$file" ]] || cs_usage_die "unknown playbook: $name (cloudsting playbook to list)"

    local run_id="pb-$(date -u +%Y%m%dT%H%M%SZ)-$$"
    local out="$CS_LOOT/playbooks/$run_id"
    mkdir -p "$out"

    printf 'PLAYBOOK\t%s\nRUN_ID\t%s\nOUT\t%s\n\n' "$name" "$run_id" "$out"

    # .play format, one step per line:
    #   module <ref> <argv…>        run a module, pass its stdout to the next step
    #   set KEY=VALUE               export for every later step
    #   stop-on-fail | continue     rule for the rest of the chain
    #   #desc: …                    one-line description for the list
    local line n=0 rc=0 stop_on_fail=1 stdin_file="$out/args.tsv"
    : > "$stdin_file"

    while IFS= read -r line; do
        [[ -z "${line// }" ]] && continue
        [[ "$line" == \#* ]] && continue
        case "$line" in
            stop-on-fail) stop_on_fail=1; continue ;;
            continue)     stop_on_fail=0; continue ;;
            set\ *)
                local kv="${line#set }"
                export "${kv?}"
                printf 'SET\t%s\n' "$kv"
                continue ;;
            require\ *)
                local v="${line#require }"
                if [ -z "${!v:-}" ]; then
                    printf 'REQUIRE\t%s\tunset — pass it: cloudsting playbook %s %s=<value>\n' "$v" "$name" "$v"
                fi
                continue ;;
            module\ *)
                local rest="${line#module }"
                local ref="${rest%% *}"
                local argv="${rest#"$ref"}"
                argv="${argv#"${argv%%[![:space:]]*}"}"   # drop the separator space
                n=$((n + 1))
                local row; row="$(cs_resolve "$ref")" || { cs_err "step $n: unknown module $ref"; rc=1; break; }
                local script; script="$(cs_script_for "$row")"
                printf 'STEP\t%s\t%s\t%s\n' "$n" "$(cs_slug "$row")" "$argv"

                # Expand the step's words so "$TARGET" and $OUT reach the
                # module resolved, not literal. eval is scoped to this one
                # argument list and the playbook is a file the operator owns.
                local -a sargs=()
                set +u
                # shellcheck disable=SC2207
                eval "sargs=( $argv )"
                set -u
                if timeout 600 bash "$script" "${sargs[@]}" <"$stdin_file" >"$out/$n-$(cs_slug "$row").tsv" 2>"$out/$n-$(cs_slug "$row").err"; then
                    cp "$out/$n-$(cs_slug "$row").tsv" "$stdin_file"
                    printf 'STEP_OK\t%s\n' "$n"
                else
                    printf 'STEP_FAIL\t%s\t%s\n' "$n" "$?"
                    rc=1
                    (( stop_on_fail )) && break
                fi
                ;;
            *) cs_err "playbook: unrecognised line: $line"; rc=1; (( stop_on_fail )) && break ;;
        esac
    done < "$file"

    printf '\nSTEPS\t%s\nRECORD\t%s\n' "$n" "$out"
    return "$rc"
}

# ── verb: findings ──────────────────────────────────────────────────
# The unified store. Every module writes TSV with its own vocabulary; this
# turns that vocabulary into one incident-shaped table so a question can be
# asked across modules instead of per-directory:
#
#   ts  module  category  severity  target  check  detail  evidence
#
# The severity is derived, not invented: `critical`/`high`/`medium`/`low`
# where the module already grades a row, `info` when it is a plain fact, and
# `clean` when the row is a passing control. The derivation lives in
# data/findings.map so it can be corrected without touching this file.
cs_cmd_findings() {
    local sub="${1:-list}"; shift || true
    local f; f="$(cs_findings_file)"

    case "$sub" in
        ingest)
            # ingest <module-ref> <tsv-file> [target] [--evidence PATH]
            local ref="${1:?module required}" tsv="${2:?tsv file required}" target="${3:-unknown}"
            [[ "${4:-}" == "--evidence" ]] && export CS_EVIDENCE="${5:-}"
            local row; row="$(cs_resolve "$ref")" || cs_usage_die "unknown module: $ref"
            [[ -r "$tsv" ]] || cs_usage_die "not readable: $tsv"
            f="$(cs_findings_ensure)"

            local slug cat; slug="$(cs_slug "$row")"; cat="$(cs_cat "$row")"
            local n=0
            # Read the file row by row. A line is a finding when it holds a
            # tab; prose, banners, indented help and blank lines are not.
            while IFS= read -r line; do
                [[ -z "${line//$'\t'/}" ]] && continue     # no tab: not a row
                [[ "$line" == \#* ]] && continue
                local key val
                key="${line%%$'\t'*}"
                val="${line#*$'\t'}"
                # indented help text: leading whitespace inside the key
                [[ "$key" == [[:space:]]* ]] && continue
                # a module header banner like "cloudsting module 15 — …"
                [[ "$key" == cloudsting* ]] && continue
                cs_findings_row "$slug" "$cat" "$target" "$key" "$val" >> "$f"
                n=$((n + 1))
            done < "$tsv"

            printf 'INGESTED\t%s\nROWS\t%s\nFILE\t%s\n' "$tsv" "$n" "$f"
            ;;
        list|"")
            [[ -r "$f" ]] || { cs_note "no findings yet: $f"; return 0; }
            local sev="${1:-}" lim="${2:-80}"
            if [[ -n "$sev" && "$sev" != *[0-9]* ]]; then
                awk -F'\t' -v s="$sev" -v l="$lim" '
                    NR==1 {print; next}
                    tolower($4)==tolower(s) {print; if (++n>=l) exit}' "$f"
            else
                awk -F'\t' -v l="${sev:-80}" 'NR==1{print} NR>1{print; if (++n>=l) exit}' "$f"
            fi
            ;;
        top)
            # worst first, grouped by severity
            [[ -r "$f" ]] || { cs_note "no findings yet: $f"; return 0; }
            awk -F'\t' 'NR>1 && $4!="info" && $4!="clean" {
                    rank = ($4=="critical"?0 : $4=="high"?1 : $4=="medium"?2 : $4=="low"?3 : 4)
                    printf "%s\t%s\t%s\t%s\t%s\t%s\n", rank, $4, $2, $5, $6, $7
                }' "$f" | sort -t$'\t' -k1,1n -k3,3 | cut -f2- | head -n "${1:-40}"
            ;;
        grep)
            local pat="${1:?pattern required}"
            [[ -r "$f" ]] || { cs_note "no findings yet: $f"; return 0; }
            awk -F'\t' -v p="$pat" 'NR==1{print;next} tolower($0) ~ tolower(p)' "$f"
            ;;
        stats)
            [[ -r "$f" ]] || { cs_note "no findings yet: $f"; return 0; }
            printf 'SEVERITY\tROWS\n'
            awk -F'\t' 'NR>1 {c[$4]++} END {for (s in c) printf "%s\t%s\n", s, c[s]}' "$f" \
                | sort -t$'\t' -k2,2nr
            printf 'MODULE\tROWS\n'
            awk -F'\t' 'NR>1 {c[$2]++} END {for (m in c) printf "%s\t%s\n", m, c[m]}' "$f" \
                | sort -t$'\t' -k2,2nr
            ;;
        correlate)
            # one row per (target, check) that more than one module reported:
            # a public bucket and a wildcard role on the same account are one
            # incident, not two findings.
            [[ -r "$f" ]] || { cs_note "no findings yet: $f"; return 0; }
            awk -F'\t' 'NR>1 && $4!="info" && $4!="clean" {
                    key = $5 "|" $6
                    if (!seen[key, $2]++) {
                        mods[key] = mods[key] (mods[key] ? "," : "") $2
                        nmods[key]++
                    }
                    if (!(key in sev)) sev[key] = $4
                    if (!(key in first)) first[key] = $7
                }
                END {
                    printf "TARGET\tCHECK\tSEVERITY\tMODULES\tDETAIL\n"
                    for (k in nmods) if (nmods[k] > 1)
                        printf "%s\t%s\t%s\t%s\n", k, sev[k], mods[k], first[k]
                }' "$f" | tr '|' '\t'
            ;;
        path) printf '%s\n' "$f" ;;
        schema) printf '%s\n' "$CS_FINDINGS_HEADER" ;;
        *) cs_usage_die "findings: unknown sub-verb $sub (list|top|ingest|grep|stats|correlate|path|schema)" ;;
    esac
}

# ── verb: completion ────────────────────────────────────────────────
cs_cmd_completion() {
    local shell="${1:-bash}"
    case "$shell" in
        bash)
            cat <<'BASH'
# bash completion for cloudsting
_cloudsting() {
    local cur prev words cword
    _init_completion 2>/dev/null || {
        cur="${COMP_WORDS[COMP_CWORD]}"
        prev="${COMP_WORDS[COMP_CWORD-1]}"
        words=("${COMP_WORDS[@]}")
        cword=$COMP_CWORD
    }

    local verbs="menu list info run deps selftest status loot playbook findings
                 registry completion man version help"

    if (( cword == 1 )); then
        COMPREPLY=( $(compgen -W "$verbs" -- "$cur") )
        return 0
    fi

    case "${words[1]}" in
        run|info|status|selftest|loot)
            if (( cword == 2 )); then
                local mods
                mods="all $(cloudsting list 2>/dev/null | cut -f2 | tr '\n' ' ')"
                COMPREPLY=( $(compgen -W "$mods" -- "$cur") )
                return 0
            fi
            if [[ "${words[1]}" == "run" ]]; then
                # past the module: hand the flags the module itself documents
                local slug="${words[2]}"
                local flags
                flags="$(cloudsting info "$slug" 2>/dev/null | awk -F'\t' '$1=="VERBS"{print $2}')"
                COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
                return 0
            fi
            ;;
        playbook)
            if (( cword == 2 )); then
                local pbs
                pbs="$(cloudsting playbook 2>/dev/null | awk 'NR>1{print $1}' | tr '\n' ' ')"
                COMPREPLY=( $(compgen -W "$pbs" -- "$cur") )
                return 0
            fi
            ;;
        findings)
            if (( cword == 2 )); then
                COMPREPLY=( $(compgen -W "list ingest grep stats path" -- "$cur") )
                return 0
            fi
            ;;
        registry)
            if (( cword == 2 )); then
                COMPREPLY=( $(compgen -W "--tsv --json --header --generate" -- "$cur") )
                return 0
            fi
            ;;
        completion)
            if (( cword == 2 )); then
                COMPREPLY=( $(compgen -W "bash zsh" -- "$cur") )
                return 0
            fi
            ;;
    esac
    return 0
}
complete -F _cloudsting cloudsting
